def render_json(document: Any, *, compact_depth: int) -> str:
    """Serialise deterministically; containers nested ``compact_depth`` deep stay on one line.

    With ``compact_depth=4`` each model in ``prices.json`` is one line, so a price change
    is a one-line diff. The text is parsed back and compared with the input, so a number
    that does not survive serialisation exactly raises instead of being written.
    """
    try:
        text = _render(document, 0, compact_depth) + "\n"
        reparsed = schema.loads_json(text)
    except (TypeError, ValueError, OverflowError) as exc:
        raise SnapshotError(f"cannot serialise output: {exc}") from exc
    if reparsed != document:
        raise SnapshotError("serialisation did not round-trip exactly")
    return text


def _render(value: Any, depth: int, compact_depth: int) -> str:
    if depth >= compact_depth or not isinstance(value, (dict, list)) or not value:
        return json.dumps(
            value, ensure_ascii=False, allow_nan=False, default=_json_number
        )
    inner = "  " * (depth + 1)
    if isinstance(value, dict):
        rows = [
            f"{inner}{json.dumps(key, ensure_ascii=False)}: "
            f"{_render(item, depth + 1, compact_depth)}"
            for key, item in value.items()
        ]
        return "{\n" + ",\n".join(rows) + "\n" + "  " * depth + "}"
    rows = [inner + _render(item, depth + 1, compact_depth) for item in value]
    return "[\n" + ",\n".join(rows) + "\n" + "  " * depth + "]"


def _json_number(value: Any) -> float:
    if isinstance(value, Decimal):
        return float(value)
    raise TypeError(f"cannot serialise {type(value).__name__}")


def write_atomically(outputs: Mapping[Path, str]) -> None:
    """Stage all files; restore prior files if a replacement fails.

    This is recoverable rollback, not a crash-atomic multi-file transaction. A
    rollback failure is explicit and preserves its backup for operator recovery.
    """
    staged: list[tuple[Path, Path]] = []
    backups: dict[Path, Path | None] = {}
    replaced: list[Path] = []
    retained: set[Path] = set()
    try:
        for target, text in outputs.items():
            if target.is_symlink():
                raise OSError(f"refusing symlink output {target}")
            if target.exists():
                handle, name = tempfile.mkstemp(
                    dir=target.parent, prefix=f".{target.name}.backup.", suffix=".tmp"
                )
                backup = Path(name)
                backups[target] = backup
                with os.fdopen(handle, "wb") as stream:
                    stream.write(target.read_bytes())
                os.chmod(backup, target.stat().st_mode & 0o777)
            else:
                backups[target] = None
            handle, name = tempfile.mkstemp(
                dir=target.parent, prefix=f".{target.name}.", suffix=".tmp"
            )
            staged.append((Path(name), target))
            with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(text)
            os.chmod(name, 0o644)
        try:
            for temporary, target in staged:
                replaced.append(
                    target
                )  # Include a signal arriving inside/after replace.
                os.replace(temporary, target)
        except BaseException as exc:
            failures = []
            if not isinstance(exc, OSError):
                retained.update(
                    backup for backup in backups.values() if backup is not None
                )
            for target in reversed(replaced):
                backup = backups[target]
                try:
                    if backup is None:
                        target.unlink(missing_ok=True)
                    else:
                        if (
                            target.exists()
                            and target.read_bytes() == backup.read_bytes()
                        ):
                            continue  # A failed replace did not modify this target.
                        handle, name = tempfile.mkstemp(
                            dir=target.parent,
                            prefix=f".{target.name}.backup.restore.",
                            suffix=".tmp",
                        )
                        restore = Path(name)
                        staged.append((restore, target))
                        with os.fdopen(handle, "wb") as stream:
                            stream.write(backup.read_bytes())
                        os.chmod(restore, backup.stat().st_mode & 0o777)
                        os.replace(restore, target)
                except BaseException:
                    failures.append(str(target))
                    if backup is not None:
                        retained.add(backup)
            if failures:
                raise OSError(
                    f"replacement failed; rollback incomplete for {failures}; backups retained {sorted(map(str, retained))}"
                ) from exc
            if not isinstance(exc, OSError):
                raise  # Preserve KeyboardInterrupt/SystemExit after restoring outputs.
            raise OSError("replacement failed; previous files restored") from exc
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)
        for backup in backups.values():
            if backup is not None and backup not in retained:
                backup.unlink(missing_ok=True)


