def build_snapshot(
    raw_bytes: bytes,
    fetched_at: datetime | str,
    *,
    retrieved_via: str = "https",
) -> dict[str, Any]:
    """Build the ``prices.json`` document from a raw models.dev payload.

    Pure: the same bytes and ``fetched_at`` always give the same document. Only the
    supported providers are kept, ordered by id; within a provider only models that
    carry a cost object are kept, ordered by id, each reduced to ``{"cost": <verbatim>}``.
    Raises :class:`SnapshotError` for any source that cannot be trusted.
    """
    try:
        fetched = schema.normalize_fetched_at(fetched_at)
    except (TypeError, ValueError) as exc:
        raise SnapshotError(f"invalid fetched_at: {exc}") from exc
    source = parse_source(raw_bytes)
    digest = hashlib.sha256(raw_bytes).hexdigest()

    providers: dict[str, Any] = {}
    for engine_id in sorted(schema.PROVIDER_MAP):
        upstream_id = schema.PROVIDER_MAP[engine_id]
        block = source.get(upstream_id)
        if not isinstance(block, dict) or not isinstance(block.get("models"), dict):
            raise SnapshotError(f"source has no usable {upstream_id!r} provider")
        if block.get("id", upstream_id) != upstream_id:
            raise SnapshotError(f"provider {upstream_id!r} carries a different id")
        models = _priced_models(upstream_id, block["models"])
        if not models:
            raise SnapshotError(f"provider {upstream_id!r} has no priced models")
        providers[engine_id] = {
            "modelsdev_provider": upstream_id,
            "source_model_count": len(block["models"]),
            "models": models,
        }

    return {
        "schema_version": schema.SCHEMA_VERSION,
        "snapshot_id": schema.derive_snapshot_id(digest, fetched),
        "fetched_at": fetched,
        "unit": schema.RATE_UNIT,
        "source": {
            "name": schema.SOURCE_NAME,
            "url": schema.SOURCE_URL,
            "retrieved_via": retrieved_via,
            "sha256": digest,
            "size_bytes": len(raw_bytes),
            "license": schema.SOURCE_LICENSE,
            "attribution": (
                "Price data derived from models.dev (https://models.dev), "
                "MIT License, Copyright (c) 2025 models.dev."
            ),
            "license_text": schema.MODELS_DEV_LICENSE_TEXT,
        },
        "providers": providers,
    }


def _priced_models(upstream_id: str, models: Mapping[str, Any]) -> dict[str, Any]:
    kept: dict[str, Any] = {}
    for model_id in sorted(models):
        entry = models[model_id]
        where = f"{upstream_id}/{model_id}"
        if not model_id:
            raise SnapshotError(f"{upstream_id}: empty model id")
        if not isinstance(entry, dict):
            raise SnapshotError(f"{where}: model entry must be an object")
        if entry.get("id", model_id) != model_id:
            raise SnapshotError(f"{where}: model id differs from its key")
        cost = entry.get("cost")
        if cost is None or cost == {}:
            continue  # no price recorded: unknown, never zero
        try:
            schema.validate_cost(cost, where)
        except schema.PricingDataError as exc:
            raise SnapshotError(str(exc)) from exc
        kept[model_id] = {"cost": cost}
    return kept


