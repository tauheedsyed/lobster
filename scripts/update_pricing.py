if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from lobster.pricing import schema  # noqa: E402

PRICING_DIR = REPO_ROOT / "lobster" / "pricing"
PROVIDERS_DIR = REPO_ROOT / "lobster" / "config" / "providers"

MAX_SOURCE_BYTES = 32 * 1024 * 1024  # the real payload is a few MB
FETCH_TIMEOUT_SECONDS = 30.0  # per socket operation
FETCH_DEADLINE_SECONDS = 120.0  # whole download
USER_AGENT = "lobster-update-pricing/1"

# Static catalogs read from the provider modules: ``KNOWN_MODELS`` on the provider
# classes and OpenRouter's curated ``_FALLBACK_MODELS``. OpenRouter's live model list
# is fetched at run time by the provider and is never inspected here.
CATALOG_ATTRIBUTES = ("KNOWN_MODELS", "_FALLBACK_MODELS")

_BLOCK_SIZE = 64 * 1024


class SnapshotError(Exception):
    """The source or the generated output is unusable; nothing was written."""


