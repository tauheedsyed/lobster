#!/usr/bin/env python3
"""Regenerate the committed LLM price snapshot from models.dev.

Why this exists
---------------
Hand-typed price tables drift. ``lobster.pricing`` instead ships a snapshot of the
public models.dev registry (MIT licensed) that is generated by this script, committed,
and reviewed in the pull request like any other source change. Nothing fetches prices
at run time; refreshing is a deliberate, reviewable act.

What it does
------------
1. Fetches https://models.dev/api.json (bounded timeout and size), or reads a local
   capture given with ``--source``.
2. Keeps only the providers the engine supports (``lobster.pricing.schema.PROVIDER_MAP``)
   and, for each model, only its ``cost`` object, verbatim. ``null``, ``0``, ``tiers`` and
   ``context_over_200k`` are preserved as found; nothing is guessed, defaulted or resolved.
3. Records provenance: source URL, raw-source sha256, size, fetch time, schema version,
   a ``snapshot_id`` derived from sha256 + fetch time, and the full MIT license text.
4. Writes ``lobster/pricing/prices.json`` and a coverage report
   (``lobster/pricing/coverage.json``) of the engine's static provider catalogs
   (read with ``ast``; nothing is imported) against the snapshot and ``overrides.json``.

Everything is computed in memory first. An unreachable, truncated, oversized or
structurally invalid source exits non-zero and leaves the existing files untouched.

Usage
-----
    python scripts/update_pricing.py
    python scripts/update_pricing.py --source models-dev-capture.json \\
        --fetched-at 2026-10-24T23:15:51Z      # deterministic, offline
"""

