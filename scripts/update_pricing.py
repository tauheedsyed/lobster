def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Regenerate lobster/pricing/prices.json from models.dev."
    )
    parser.add_argument(
        "--source",
        type=Path,
        help="read this local models.dev capture instead of fetching",
    )
    parser.add_argument(
        "--fetched-at",
        help="when the --source capture was taken, ISO-8601 with timezone",
    )
    parser.add_argument("--output-dir", type=Path, default=PRICING_DIR)
    parser.add_argument("--providers-dir", type=Path, default=PROVIDERS_DIR)
    args = parser.parse_args(argv)
    if (args.source is None) != (args.fetched_at is None):
        parser.error("--source and --fetched-at must be given together")
    return args


def main(
    argv: Sequence[str] | None = None,
    *,
    fetch: Callable[[], bytes] = fetch_source,
    now: Callable[[], datetime] = _utc_now,
) -> int:
    args = _parse_args(argv)
    output_dir: Path = args.output_dir
    try:
        if args.source is not None:
            raw, fetched_at, via = (
                read_local_source(args.source),
                args.fetched_at,
                "file",
            )
        else:
            raw = fetch()
            fetched_at, via = now(), "https"
        snapshot = build_snapshot(raw, fetched_at, retrieved_via=via)
        coverage = build_coverage(
            snapshot,
            load_overrides(output_dir / "overrides.json"),
            extract_catalogs(args.providers_dir),
        )
        outputs = {
            output_dir / "prices.json": render_json(snapshot, compact_depth=4),
            output_dir / "coverage.json": render_json(coverage, compact_depth=5),
        }
        write_atomically(outputs)
    except SnapshotError as exc:
        print(
            f"update_pricing: error: {exc}; existing files left untouched",
            file=sys.stderr,
        )
        return 1
    except OSError as exc:
        # Staging precedes replacement, but multiple files are not one filesystem
        # transaction. Never promise rollback after an I/O failure during replacement.
        print(
            f"update_pricing: I/O error: {exc}; inspect outputs before review",
            file=sys.stderr,
        )
        return 1
    _report(snapshot, coverage, outputs)
    return 0


def _report(
    snapshot: Mapping[str, Any],
    coverage: Mapping[str, Any],
    outputs: Mapping[Path, str],
) -> None:
    print(
        f"snapshot {snapshot['snapshot_id']} (source sha256 {snapshot['source']['sha256']})"
    )
    for engine_id, block in snapshot["providers"].items():
        print(
            f"  {engine_id:<11} {len(block['models']):>4} priced"
            f" / {block['source_model_count']} in {block['modelsdev_provider']}"
        )
    totals = coverage["totals"]
    print(
        f"engine catalogs: {totals['priced']} of {totals['engine_models']} models priced, "
        f"{totals['unpriced']} unpriced (see coverage.json)"
    )
    for path in outputs:
        print(f"wrote {path}")


if __name__ == "__main__":
    sys.exit(main())
