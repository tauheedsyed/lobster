def extract_catalogs(providers_dir: Path | str) -> dict[str, Any]:
    """Read the engine's static model catalogs with ``ast`` (nothing is imported).

    Looks for ``KNOWN_MODELS`` / ``_FALLBACK_MODELS`` list literals of ``ModelInfo(...)``
    calls in ``*_provider.py`` and groups model names by their literal ``provider=``.
    Entries whose name or provider is not a plain string literal are listed under
    ``unresolved`` rather than guessed.
    """
    directory = Path(providers_dir)
    files = sorted(directory.glob("*_provider.py"))
    if not files:
        raise SnapshotError(f"no *_provider.py files in {directory}")
    models: dict[str, set[str]] = {}
    sources: dict[str, set[str]] = {}
    unresolved: list[str] = []
    for file in files:
        try:
            tree = ast.parse(file.read_text(encoding="utf-8"), filename=str(file))
        except (OSError, SyntaxError, ValueError) as exc:
            raise SnapshotError(
                f"cannot read catalogs from {file.name}: {exc}"
            ) from exc
        for attribute, elements in _catalog_literals(tree):
            if elements is None:  # e.g. ``BASE + [...]``: not statically readable
                unresolved.append(f"{file.name}:{attribute}")
                continue
            for index, element in enumerate(elements):
                name, provider = _model_info_fields(element)
                if name is None or provider is None:
                    unresolved.append(f"{file.name}:{attribute}[{index}]")
                    continue
                models.setdefault(provider, set()).add(name)
                sources.setdefault(provider, set()).add(f"{file.name}:{attribute}")
    return {
        "providers": {
            provider: {
                "models": sorted(models[provider]),
                "sources": sorted(sources[provider]),
            }
            for provider in sorted(models)
        },
        "unresolved": sorted(unresolved),
    }


def _catalog_literals(tree: ast.Module) -> list[tuple[str, list[ast.expr] | None]]:
    """Catalog assignments as ``(attribute, elements)``; ``None`` if not a list literal."""
    bodies = [tree.body] + [n.body for n in tree.body if isinstance(n, ast.ClassDef)]
    found: list[tuple[str, list[ast.expr] | None]] = []
    for body in bodies:
        for statement in body:
            if isinstance(statement, ast.Assign):
                names = [t.id for t in statement.targets if isinstance(t, ast.Name)]
            elif isinstance(statement, ast.AnnAssign) and isinstance(
                statement.target, ast.Name
            ):
                names = [statement.target.id]
            else:
                continue
            value = statement.value
            if value is None:  # a bare annotation assigns nothing
                continue
            elements = (
                list(value.elts) if isinstance(value, (ast.List, ast.Tuple)) else None
            )
            found.extend(
                (name, elements) for name in names if name in CATALOG_ATTRIBUTES
            )
    return found


def _model_info_fields(node: ast.expr) -> tuple[str | None, str | None]:
    """Return the literal ``(name, provider)`` of a ``ModelInfo(...)`` call, if plain."""
    if not isinstance(node, ast.Call):
        return None, None
    func = node.func
    called = func.id if isinstance(func, ast.Name) else getattr(func, "attr", None)
    if called != "ModelInfo":
        return None, None
    # ModelInfo(name, display_name, description, provider, ...)
    positional = ("name", "display_name", "description", "provider")
    arguments: dict[str, ast.expr] = dict(zip(positional, node.args))
    arguments.update({kw.arg: kw.value for kw in node.keywords if kw.arg})
    return _string_literal(arguments.get("name")), _string_literal(
        arguments.get("provider")
    )


def _string_literal(node: ast.expr | None) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def build_coverage(
    snapshot: Mapping[str, Any],
    overrides: Sequence[schema.Override],
    catalogs: Mapping[str, Any],
) -> dict[str, Any]:
    """Report which static engine catalog models have a rate (pure, deterministic).

    ``priced_by_snapshot`` / ``priced_by_override`` count models with a rate and
    ``unpriced`` lists the rest. ``ollama`` and ``omics-os`` are reported as
    non-market providers rather than as gaps.
    """
    catalog_providers = catalogs["providers"]
    override_keys = {(o.provider, o.model_id) for o in overrides}
    market: dict[str, Any] = {}
    totals = {"engine_models": 0, "priced": 0, "unpriced": 0}
    for provider in sorted(schema.PROVIDER_MAP):
        names = catalog_providers.get(provider, {}).get("models", [])
        in_snapshot = snapshot["providers"][provider]["models"]
        by_override = [n for n in names if (provider, n) in override_keys]
        by_snapshot = [
            n for n in names if (provider, n) not in override_keys and n in in_snapshot
        ]
        unpriced = [
            n
            for n in names
            if (provider, n) not in override_keys and n not in in_snapshot
        ]
        market[provider] = {
            "sources": catalog_providers.get(provider, {}).get("sources", []),
            "engine_models": len(names),
            "priced_by_snapshot": len(by_snapshot),
            "priced_by_override": len(by_override),
            "unpriced": unpriced,
        }
        totals["engine_models"] += len(names)
        totals["priced"] += len(by_snapshot) + len(by_override)
        totals["unpriced"] += len(unpriced)

    excluded = {
        provider: {
            "market_provider": False,
            "reason": reason,
            "engine_models": len(catalog_providers.get(provider, {}).get("models", [])),
        }
        for provider, reason in sorted(schema.NON_MARKET_PROVIDERS.items())
    }
    known = set(schema.PROVIDER_MAP) | set(schema.NON_MARKET_PROVIDERS)
    unmapped = {
        provider: {"engine_models": len(info["models"])}
        for provider, info in sorted(catalog_providers.items())
        if provider not in known
    }
    shadowing = sorted(
        f"{o.provider}/{o.model_id}"
        for o in overrides
        if o.model_id in snapshot["providers"][o.provider]["models"]
    )
    return {
        "schema_version": schema.SCHEMA_VERSION,
        "snapshot_id": snapshot["snapshot_id"],
        "description": (
            "Static engine model catalogs checked against prices.json and overrides.json. "
            "Generated by scripts/update_pricing.py. Live provider catalogs, such as the "
            "OpenRouter model list, are not inspected."
        ),
        "market_providers": market,
        "excluded_providers": excluded,
        "unmapped_providers": unmapped,
        "unresolved_catalog_entries": catalogs["unresolved"],
        "overrides": {"count": len(overrides), "shadowing_snapshot": shadowing},
        "totals": totals,
    }


def load_overrides(path: Path | str) -> tuple[schema.Override, ...]:
    """Load and validate ``overrides.json``; a missing file means no overrides."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except FileNotFoundError:
        return ()
    except OSError as exc:
        raise SnapshotError(f"cannot read {path}: {exc}") from exc
    try:
        return schema.validate_overrides(schema.loads_json(text))
    except schema.PricingDataError as exc:
        raise SnapshotError(f"{path}: {exc}") from exc


