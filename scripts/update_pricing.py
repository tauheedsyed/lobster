def fetch_source(
    url: str = schema.SOURCE_URL,
    *,
    timeout: float = FETCH_TIMEOUT_SECONDS,
    deadline: float = FETCH_DEADLINE_SECONDS,
    max_bytes: int = MAX_SOURCE_BYTES,
    urlopen: Callable[..., Any] = urllib.request.urlopen,
    clock: Callable[[], float] = time.monotonic,
) -> bytes:
    """Bound the ENTIRE fetch, including DNS/open/headers/redirects and body reads.

    A daemon worker permits an absolute caller deadline even while an opener is
    blocked. Available transports are shut down; late responses are closed before
    any body is read. CLI failure cannot proceed to validation or writing files.
    """
    absolute_deadline = time.monotonic() + deadline
    completed, cancelled = threading.Event(), threading.Event()
    result: dict[str, Any] = {}
    active: dict[str, Any] = {}

    def stop_response(response):
        transport = getattr(
            getattr(getattr(response, "fp", None), "raw", None), "_sock", None
        )
        try:
            if transport is not None:
                transport.shutdown(socket.SHUT_RDWR)
            else:
                close = getattr(response, "close", None)
                if close is not None:
                    threading.Thread(
                        target=close, name="pricing-source-close", daemon=True
                    ).start()
        except OSError:
            pass

    def tracked_open(*args, **kwargs):
        response = urlopen(*args, **kwargs)
        active["response"] = response
        if cancelled.is_set():
            stop_response(response)
            raise SnapshotError(f"download exceeded {deadline:g}s")
        return response

    def worker():
        try:
            result["body"] = _fetch_source_body(
                url,
                timeout=min(timeout, deadline),
                deadline=deadline,
                max_bytes=max_bytes,
                urlopen=tracked_open,
                clock=clock,
            )
        except BaseException as exc:
            result["error"] = exc
        finally:
            completed.set()

    thread = threading.Thread(target=worker, name="pricing-source-fetch", daemon=True)
    thread.start()
    try:
        if not completed.wait(max(0, absolute_deadline - time.monotonic())):
            raise SnapshotError(f"download exceeded {deadline:g}s")
        if "error" in result:
            raise result["error"]
        return result["body"]
    except BaseException:
        cancelled.set()
        if "response" in active:
            stop_response(active["response"])
        raise


def _fetch_source_body(
    url: str = schema.SOURCE_URL,
    *,
    timeout: float = FETCH_TIMEOUT_SECONDS,
    deadline: float = FETCH_DEADLINE_SECONDS,
    max_bytes: int = MAX_SOURCE_BYTES,
    urlopen: Callable[..., Any] = urllib.request.urlopen,
    clock: Callable[[], float] = time.monotonic,
) -> bytes:
    """Download ``url`` over https, bounded in time and size, and return the raw bytes."""
    if not url.startswith("https://"):
        raise SnapshotError(f"refusing non-https source URL: {url}")
    request = urllib.request.Request(
        url, headers={"Accept": "application/json", "User-Agent": USER_AGENT}
    )
    started = clock()
    chunks: list[bytes] = []
    total = 0
    try:
        with urlopen(  # nosec B310 # https-only, checked above and after redirects
            request, timeout=timeout, context=_ssl_context()
        ) as response:
            status = getattr(response, "status", 200)
            if status != 200:
                raise SnapshotError(f"{url} answered HTTP {status}")
            final_url = response.geturl()
            if not str(final_url).startswith("https://"):
                raise SnapshotError(f"redirected to a non-https URL: {final_url}")
            declared = response.headers.get("Content-Length")
            if (
                declared is not None
                and declared.isdigit()
                and int(declared) > max_bytes
            ):
                raise SnapshotError(
                    f"source is {declared} bytes, over the {max_bytes} byte limit"
                )
            if declared is not None and not declared.isdigit():
                raise SnapshotError("invalid Content-Length")
            remaining = deadline - (clock() - started)
            if remaining <= 0:
                raise SnapshotError(f"download exceeded {deadline:g}s")
            expired = threading.Event()

            def interrupt_read():
                expired.set()
                # close() alone can wait on a buffered reader lock. Shutdown the
                # underlying socket first to interrupt even trickle/chunked reads.
                transport = getattr(
                    getattr(getattr(response, "fp", None), "raw", None), "_sock", None
                )
                try:
                    if transport is not None:
                        transport.shutdown(socket.SHUT_RDWR)
                    else:
                        close = getattr(response, "close", None)
                        if close is not None:
                            close()
                except OSError:
                    pass

            timer = threading.Timer(remaining, interrupt_read)
            timer.daemon = True
            timer.start()
            try:
                while True:
                    chunk = response.read(_BLOCK_SIZE)
                    if expired.is_set() or clock() - started > deadline:
                        raise SnapshotError(f"download exceeded {deadline:g}s")
                    if not chunk:
                        break
                    total += len(chunk)
                    if total > max_bytes:
                        raise SnapshotError(
                            f"source exceeds the {max_bytes} byte limit"
                        )
                    chunks.append(chunk)
            except (OSError, http.client.HTTPException) as exc:
                if expired.is_set():
                    raise SnapshotError(f"download exceeded {deadline:g}s") from exc
                raise
            finally:
                timer.cancel()
            if declared is not None and total != int(declared):
                raise SnapshotError(
                    f"Content-Length {declared} differs from received {total} bytes"
                )
    except (OSError, http.client.HTTPException) as exc:  # URLError is an OSError
        raise SnapshotError(f"could not fetch {url}: {exc}") from exc
    return b"".join(chunks)


def _ssl_context() -> ssl.SSLContext:
    """Verify certificates against the system store, plus certifi's bundle if present.

    The extra bundle covers python.org builds that ship without a CA store.
    """
    context = ssl.create_default_context()
    try:
        import certifi
    except ImportError:
        return context
    context.load_verify_locations(cafile=certifi.where())
    return context


def read_local_source(path: Path | str, *, max_bytes: int = MAX_SOURCE_BYTES) -> bytes:
    """Read a local capture, refusing anything over ``max_bytes``."""
    try:
        with open(path, "rb") as handle:
            data = handle.read(max_bytes + 1)
    except OSError as exc:
        raise SnapshotError(f"cannot read source {path}: {exc}") from exc
    if len(data) > max_bytes:
        raise SnapshotError(f"{path} exceeds the {max_bytes} byte limit")
    return data


def parse_source(raw_bytes: bytes) -> dict[str, Any]:
    """Decode and parse the models.dev payload (exact decimals, no duplicate keys)."""
    if not raw_bytes:
        raise SnapshotError("source is empty")
    try:
        document = schema.loads_json(raw_bytes.decode("utf-8"))
    except UnicodeDecodeError as exc:
        raise SnapshotError(f"source is not UTF-8: {exc}") from exc
    except schema.PricingDataError as exc:
        raise SnapshotError(f"source is not usable JSON: {exc}") from exc
    if not isinstance(document, dict):
        raise SnapshotError("source must be a JSON object keyed by provider id")
    return document


